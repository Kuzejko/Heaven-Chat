function createSvgAvatar(bgGradient, symbol, textColor = "#ffffff") {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200" width="200" height="200">
    <defs>
      <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgGradient[0]}"/>
        <stop offset="100%" stop-color="${bgGradient[1]}"/>
      </linearGradient>
    </defs>
    <rect width="200" height="200" rx="32" fill="url(#g)"/>
    <circle cx="100" cy="100" r="76" fill="rgba(0,0,0,0.2)" stroke="rgba(255,255,255,0.15)" stroke-width="2"/>
    <text x="100" y="118" font-family="system-ui, -apple-system, sans-serif" font-size="58" text-anchor="middle" fill="${textColor}">${symbol}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

